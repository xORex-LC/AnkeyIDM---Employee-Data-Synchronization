"""Ошибки источника — доменный контракт отказов адаптера источника

Модуль определяет типизированные исключения, которыми адаптеры источников сообщают
об отказах на границе `RowSource`. Эти исключения принадлежат доменному
порту, чтобы `Extractor` мог классифицировать ошибки без импорта infra-слоя.

Ответственность:
    - Описывать базовый тип отказа адаптера источника.
    - Разделять ошибки чтения и ошибки разбора источника.

Вне зоны ответственности:
    - Маппинг исключений конкретных библиотек и форматов.
    - Создание `DiagnosticItem` и выбор diagnostic policy.
"""

from __future__ import annotations


class SourceAdapterError(Exception):
    """Базовый отказ адаптера источника на границе `RowSource`.

    Границы:
        - Не содержит diagnostic-код и не зависит от `ErrorCatalog`.
        - Не описывает конкретный storage backend или формат источника.
    """


class SourceReadError(SourceAdapterError):
    """Ошибка доступа или чтения данных источника."""


class SourceParseError(SourceAdapterError):
    """Ошибка структурного разбора данных источника."""
