"""Нормализация значений источника — общий контракт extract-границы

Модуль определяет формат-агностичную политику приведения raw-значений
источника к `str | None`. Эта политика едина для CSV и будущих источников,
чтобы типизация оставалась ответственностью Normalize-стадии.

Ответственность:
    - Приводить non-null значения к строкам.
    - Применять trim и null-token политику.
    - Сохранять значимые строковые значения без бизнес-интерпретации.

Вне зоны ответственности:
    - Приведение к числам, датам, bool и другим доменным типам.
    - Валидация допустимых значений конкретного поля.
"""

from __future__ import annotations


class ValueNormalizer:
    """Нормализует сырое значение источника к контракту `str | None`."""

    def normalize(self, value: object) -> str | None:
        """Вернуть строковое представление значения или `None` для null-токена."""
        if value is None:
            return None
        text = str(value).strip()
        if text == "" or text.lower() == "null":
            return None
        return text
